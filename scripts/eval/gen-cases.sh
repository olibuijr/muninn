#!/usr/bin/env bash
# Generate retrieval eval cases for one repo from the live index (read-only psql).
#
#   scripts/eval/gen-cases.sh <repo> <n> [seed] > scripts/eval/cases-<repo>.tsv
#
# Samples symbol chunks deterministically (order by md5(hash || seed)) on the repo's `main`
# branch and writes up to n cases, `query<TAB>repo<TAB>path#symbol<TAB>tag`:
#   doc   the first sentence (>= 4 words) of the item's doc comment: ix_sym_defs.doc when the
#         repo has SCIP symbols, else the `///`/`//`/`#` comment block right above the item
#         (the chunker leaves those lines in the preceding window chunk) or at the top of
#         the chunk text;
#   name  the symbol split into words with a kind word in front (`fn parse http request`).
# Roughly half doc, the rest name. Names defined in more than 3 files of the repo (`new`,
# `fmt`, `default`, ...) and one-word names under 6 letters are skipped as unanswerable; a name
# defined in 2-3 files lists all of them as alternatives. Repos without symbol chunks (Swift has
# window chunks only) get `path` cases instead: the file name's words as query, `path`
# expected, sampled from ix_files.
#
# Needs MUNINN_PG_URL (read from ~/.config/muninn/index.env when unset), psql and python3.
set -euo pipefail
repo=${1:?usage: gen-cases.sh <repo> <n> [seed]}
n=${2:?usage: gen-cases.sh <repo> <n> [seed]}
seed=${3:-muninn-eval}
branch=${BRANCH:-main}
if [[ -z "${MUNINN_PG_URL:-}" && -f ~/.config/muninn/index.env ]]; then
  # shellcheck disable=SC1090
  . ~/.config/muninn/index.env
fi
: "${MUNINN_PG_URL:?MUNINN_PG_URL unset}"

skip='(^|/)(vendor|third_party|third-party|node_modules|target|dist|build|generated|gen|\.git)/|\.min\.|_generated\.|\.pb\.|(^|/)bindings\.rs$'
kinds='{function_item,struct_item,enum_item,trait_item,macro_definition,function_declaration,class_declaration,interface_declaration,enum_declaration,method_definition}'

psql_json() {
  psql "$MUNINN_PG_URL" -X -q -At -v ON_ERROR_STOP=1 \
    -v repo="$repo" -v branch="$branch" -v seed="$seed" -v n="$n" -v skip="$skip" -v kinds="$kinds" \
    -c "set default_transaction_read_only = on" -f -
}

nsym=$(psql_json <<<"select count(*) from ix_chunks where repo = :'repo' and symbol <> '' and kind = any(:'kinds'::text[]);")
if [[ "$nsym" == 0 ]]; then
  IFS= read -r -d '' py <<'PY' || true
import json, re, sys
rows = json.loads(sys.stdin.read() or "[]") or []
repo, n = sys.argv[1], int(sys.argv[2])
words = re.compile(r"[A-Z0-9]+(?=[A-Z][a-z])|[A-Z]?[a-z0-9]+|[A-Z0-9]+")
seen, out = set(), []
for r in rows:
    leaf = r["path"].rsplit("/", 1)[-1].rsplit(".", 1)[0]
    q = " ".join(w.lower() for w in words.findall(leaf))
    if len(q.split()) < 2 or q in seen:
        continue
    seen.add(q)
    out.append(f"{q}\t{repo}\t{r['path']}\tpath")
    if len(out) >= n:
        break
print(f"# generated by scripts/eval/gen-cases.sh {repo} {n} {sys.argv[3]} (path cases: no symbol chunks)")
print("\n".join(out))
PY
  IFS= read -r -d '' sql <<'SQL' || true
select json_agg(t) from (
  select f.path from ix_files f
  where f.repo = :'repo' and f.branch = :'branch' and f.path !~ :'skip'
    and f.path ~ '\.(swift|rs|ts|tsx|kt|py|go|m|c|cc|cpp|h)$'
  order by md5(f.path || :'seed') limit (:n * 3)
) t;
SQL
  psql_json <<<"$sql" | python3 -c "$py" "$repo" "$n" "$seed"
  exit 0
fi

IFS= read -r -d '' py <<'PY' || true
import json, re, sys
rows = json.loads(sys.stdin.read() or "[]") or []
repo, n, seed = sys.argv[1], int(sys.argv[2]), sys.argv[3]
KIND = {"function_item": "fn", "struct_item": "struct", "enum_item": "enum", "trait_item": "trait",
        "macro_definition": "macro", "function_declaration": "function", "class_declaration": "class",
        "interface_declaration": "interface", "enum_declaration": "enum", "method_definition": "method"}
words = re.compile(r"[A-Z0-9]+(?=[A-Z][a-z])|[A-Z]?[a-z0-9]+|[A-Z0-9]+")
comment = re.compile(r"^\s*(///?!?|#(?![\[!])|/\*\*?|\*/?)\s?")

def is_comment(l):
    s = l.strip()
    return s.startswith("//") or s.startswith("/*") or s.startswith("*") or (s.startswith("#") and not s.startswith("#[") and not s.startswith("#!"))

def block_above(before):
    lines, out = before.split("\n"), []
    for l in reversed(lines):
        s = l.strip()
        if s.startswith("#[") or s.startswith("@"):   # attributes / decorators between doc and item
            if out:
                break
            continue
        if not is_comment(l) or s.startswith("//!"):
            break
        out.append(l)
    return list(reversed(out))

def block_top(text):
    out = []
    for l in text.split("\n"):
        if is_comment(l):
            out.append(l)
        elif out or l.strip():
            break
    return out

def sentence(lines):
    t = " ".join(comment.sub("", l).strip() for l in lines)
    t = re.sub(r"\s+", " ", t.replace("`", "")).strip()
    t = re.split(r"(?<=[.!?:;])\s|\s#\s", t, maxsplit=1)[0].rstrip(".:;")
    ws = t.split()
    if len(ws) < 4 or not re.search(r"[A-Za-z]{3}", t) or "SAFETY" in t or "TODO" in t:
        return None
    return " ".join(ws[:24])

docs, names, seen, qseen = [], [], set(), set()
for r in rows:
    key = f"{r['path']}#{r['symbol']}"
    if key in seen:
        continue
    seen.add(key)
    d = None
    if r.get("doc"):
        d = sentence(r["doc"].split("\n"))
    if not d and r.get("before"):
        d = sentence(block_above(r["before"]))
    if not d:
        d = sentence(block_top(r["text"]))
    if d and len(docs) < n // 2:
        docs.append(f"{d}\t{repo}\t{key}\tdoc")
        continue
    parts = [w.lower() for w in words.findall(r["symbol"])]
    defs = sorted(r["defs"] or [r["path"]])
    if len(defs) > 3 or not parts or (len(parts) < 2 and len(r["symbol"]) < 6):
        continue
    q = " ".join([KIND.get(r["kind"], r["kind"])] + parts)
    if q in qseen:
        continue
    qseen.add(q)
    # every file defining the name is a right answer
    exp = "|".join(f"{p}#{r['symbol']}" for p in defs)
    names.append(f"{q}\t{repo}\t{exp}\tname")
out = docs + names[: n - len(docs)]
print(f"# generated by scripts/eval/gen-cases.sh {repo} {n} {seed}")
print("# query\trepo\texpected\ttag")
print("\n".join(out))
PY
IFS= read -r -d '' sql <<'SQL' || true
with c as (
  select c.hash, c.path, c.symbol, c.kind, c.start_line, c.text
  from ix_chunks c
  where c.repo = :'repo' and c.symbol <> '' and c.kind = any(:'kinds'::text[])
    and c.path !~ :'skip'
    and exists (select 1 from ix_files f where f.repo = c.repo and f.branch = :'branch'
                and f.path = c.path and c.hash = any(f.hashes))
    -- first chunk of the symbol only (oversized items are split, the rest have no header)
    and not exists (select 1 from ix_chunks p where p.repo = c.repo and p.path = c.path
                    and p.symbol = c.symbol and p.start_line < c.start_line
                    and p.end_line >= c.start_line - 1)
  order by md5(c.hash || :'seed') limit (:n * 4)
)
select json_agg(t) from (
  select c.path, c.symbol, c.kind, c.start_line, c.text,
    (select d.doc from ix_sym_defs d where d.repo = :'repo' and d.path = c.path
       and d.name = c.symbol and coalesce(d.doc, '') <> ''
       and d.start_line between c.start_line - 1 and c.start_line + 3
     order by abs(d.start_line - c.start_line) limit 1) as doc,
    (select array_to_string((string_to_array(w.text, E'\n'))[1:(c.start_line - w.start_line)], E'\n')
       from ix_chunks w join ix_files f on f.repo = w.repo and f.path = w.path
         and f.branch = :'branch' and w.hash = any(f.hashes)
     where w.repo = :'repo' and w.path = c.path and w.kind = 'window'
       and w.start_line < c.start_line and w.end_line >= c.start_line - 1
     order by w.start_line desc limit 1) as before,
    (select array_agg(distinct x.path) from ix_chunks x where x.repo = :'repo' and x.symbol = c.symbol
       and x.kind = any(:'kinds'::text[]) and x.path !~ :'skip') as defs
  from c order by md5(c.hash || :'seed')
) t;
SQL
psql_json <<<"$sql" | python3 -c "$py" "$repo" "$n" "$seed"
